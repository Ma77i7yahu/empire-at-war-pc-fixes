"""Builds the patch tables for the Empire at War camera mod installer.

The exe patches are taken from the installed, in-game-tested StarWarsG.exe of each game
(diffed against its StarWarsG.exe.orig), and the "Unlocked" camera block from the installed
Data\\XML\\TacticalCameras.xml, so the installer reproduces exactly what was tested.  Outputs:
  PatchData.cs        - embedded tables for Installer.cs
  ../dist/PATCHES.txt - byte listing + disassembly of every change
"""
import hashlib, os, re, struct, sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else r"F:\Game Files\Steam\steamapps\common\Star Wars Empire at War"
HERE = os.path.dirname(os.path.abspath(__file__))
GAMES = [("eaw", "GameData", "Empire at War"), ("foc", "corruption", "Forces of Corruption")]
IMAGE_BASE = 0x140000000

def rd(*p): return open(os.path.join(ROOT, *p), "rb").read()
def md5(b): return hashlib.md5(b).hexdigest()

def runs(a, b, gap=8):
    spans, i = [], 0
    assert len(a) == len(b)
    while i < len(a):
        if a[i] != b[i]:
            j = i
            while j < len(a) and a[j] != b[j]: j += 1
            if spans and i - spans[-1][1] <= gap: spans[-1][1] = j
            else: spans.append([i, j])
            i = j
        else: i += 1
    return [(s, a[s:e], b[s:e]) for s, e in spans]  # (offset, old, new)

def sections(exe):
    pe = struct.unpack_from("<I", exe, 0x3c)[0]
    n = struct.unpack_from("<H", exe, pe + 6)[0]
    sh = pe + 24 + struct.unpack_from("<H", exe, pe + 20)[0]
    out = []
    for k in range(n):
        o = sh + 40 * k
        name = exe[o:o + 8].rstrip(b"\0").decode()
        vsz, va, rs, ro = struct.unpack_from("<IIII", exe, o + 8)
        out.append((name, va, vsz, ro, rs, o))
    return out

def off2va(exe, off):
    for name, va, vsz, ro, rs, _ in sections(exe):
        if ro <= off < ro + rs: return IMAGE_BASE + va + off - ro
    return None

UNLOCKED = re.compile(rb'[ \t]*(<!--[^\r\n]*-->\r\n)?[ \t]*<TacticalCamera Name="Unlocked">.*?</TacticalCamera>', re.S)

def cs_bytes(b): return "new byte[]{" + ",".join("0x%02X" % x for x in b) + "}"
def cs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t") + '"'

cs = ["// Generated by gen.py - do not edit.", "static class PatchData {"]
txt = ["Empire at War - Force Commander-style camera mod: every change it makes", "=" * 70, ""]
try:
    from capstone import Cs, CS_ARCH_X86, CS_MODE_64
    md = Cs(CS_ARCH_X86, CS_MODE_64)
except ImportError:
    md = None

for key, d, title in GAMES:
    orig, mod = rd(d, "StarWarsG.exe.orig"), rd(d, "StarWarsG.exe")
    rr = runs(orig, mod)
    assert len(rr) == 3, rr
    tc = rd(d, "Data", "XML", "TacticalCameras.xml")
    m = UNLOCKED.search(tc)
    assert m and m.group(1), "no Unlocked block with the mod comment in " + d
    block = m.group(0).decode("latin1")
    cs.append("    public const string %sOriginalMd5 = \"%s\";" % (key.capitalize(), md5(orig)))
    cs.append("    public const string %sPatchedMd5 = \"%s\";" % (key.capitalize(), md5(mod)))
    cs.append("    public static readonly Run[] %sRuns = {" % key.capitalize())
    for off, old, new in rr:
        cs.append("        new Run(0x%X, %s, %s)," % (off, cs_bytes(old), cs_bytes(new)))
    cs.append("    };")
    cs.append("    public const string %sUnlockedBlock = %s;" % (key.capitalize(), cs_str(block)))

    txt += ["%s  (%s\\StarWarsG.exe)" % (title, d), "-" * 70,
            "Original MD5 %s, patched MD5 %s, size %d" % (md5(orig).upper(), md5(mod).upper(), len(orig)), ""]
    for off, old, new in rr:
        va = off2va(orig, off)
        txt.append("file offset 0x%X%s, %d bytes" % (off, "" if va is None else " (VA 0x%X)" % va, len(new)))
        hdr = next((s for s in sections(orig) if s[5] <= off < s[5] + 40), None)
        if hdr:
            txt.append("  %s section header: VirtualSize 0x%X -> 0x%X (= SizeOfRawData, maps the code cave)" %
                       (hdr[0], hdr[2], struct.unpack_from("<I", mod, hdr[5] + 8)[0]))
        else:
            txt.append("  old: " + ("unused zero padding at the end of .text" if not any(old) else old.hex(" ")))
            txt.append("  new: " + new.hex(" "))
            if md and va is not None:
                for ins in md.disasm(new, va):
                    txt.append("    %x: %s %s" % (ins.address, ins.mnemonic, ins.op_str))
        txt.append("")
    txt += ["Data\\XML\\GameConstants.xml (written from the game's own MEG archives):",
            "  <Land_Tactical_Camera_Locked> True -> False  (land battles use the \"Unlocked\" camera)", "",
            "Data\\XML\\TacticalCameras.xml (written from the game's own MEG archives), \"Unlocked\" camera replaced with:", ""]
    txt += ["  " + l for l in block.splitlines()]
    txt.append("")

cs.append("}")
open(os.path.join(HERE, "PatchData.cs"), "w", newline="\r\n").write("\n".join(cs) + "\n")
os.makedirs(os.path.join(HERE, "..", "dist"), exist_ok=True)
open(os.path.join(HERE, "..", "dist", "PATCHES.txt"), "w", newline="\r\n").write("\n".join(txt) + "\n")
print("ok")
